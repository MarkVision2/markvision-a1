export interface BuildBriefInput {
  styleId: StyleId;
  userBrief: string;
  format?: { aspect?: string | null; lang?: string | null; variants?: number | null };
  color?: { id?: string | null; label?: string | null; swatch?: string | null } | null;
  angles?: { id: string; label: string; description: string }[];
  /** Если режим АВТО — список кандидатов, чтобы AI мог выбрать. */
  autoCandidates?: { id: string; label: string; description: string }[] | null;
}

export interface BuiltBrief {
  /** Структурированные параметры стиля. */
  structured: StyleBrief;
  /** Готовый текстовый промпт со всеми инструкциями + бриф пользователя. */
  technicalBrief: string;
  /** Negative prompt — чего избегать. */
  avoid: string[];
}

/**
 * Собирает финальный технический бриф для одного стиля:
 * берёт шаблон промпта стиля, подставляет {{userBrief}} и дополняет
 * параметрами формата (aspect, lang, основной цвет, ракурсы).
 */
export function buildStyleBrief(input: BuildBriefInput): BuiltBrief {
  const base = STYLE_BRIEFS[input.styleId] ?? STYLE_BRIEFS.auto;
  const userBrief =
    input.userBrief?.trim() || "клиент не оставил описание — используй best-practice по нише";

  const formatLines: string[] = [];
  if (input.format?.aspect) {
    // Aspect-ratio модели часто игнорируют, если просто упомянуть — нужен жёсткий accent.
    // Дублируем размер в пикселях для популярных пресетов, чтобы image-API не свалилось на дефолтный квадрат.
    const sizeMap: Record<string, string> = {
      "1:1": "1024×1024",
      "4:5": "1024×1280",
      "9:16": "768×1344",
      "16:9": "1344×768",
      "3:4": "1024×1365",
      "21:9": "1536×658",
    };
    const sizeHint = sizeMap[input.format.aspect];
    formatLines.push(
      `КРИТИЧНО — соотношение сторон строго ${input.format.aspect}${sizeHint ? ` (${sizeHint} px)` : ""}. ` +
        `НЕ 1:1, НЕ квадрат, НЕ другой формат — только ${input.format.aspect}. ` +
        `Кадрируй, компонуй и обрезай под ${input.format.aspect}; все важные элементы должны быть внутри этого кадра, не за его пределами.`,
    );
  }
  if (input.format?.lang) {
    const langMap: Record<string, string> = { ru: "русский", kz: "казахский", en: "английский" };
    const lang = langMap[input.format.lang] ?? input.format.lang;
    const isCyrillic = input.format.lang === "ru" || input.format.lang === "kz";
    formatLines.push(`Язык текста на креативе: ${lang}.`);
    if (isCyrillic) {
      // Image-модели регулярно ломают кириллицу: латинская транслитерация, перевёрнутые буквы,
      // отсутствующие диакритики (ё, й, ұ, қ, ң, ө, ә, і, һ). Даём жёсткий гайдрейл и просим
      // короткие фразы — длинный кириллический текст почти гарантированно рендерится с ошибками.
      formatLines.push(
        `КРИТИЧНО ВАЖНО про текст на креативе (язык: ${lang}):` +
          `\n  • Весь текст — строго кириллицей, БЕЗ латинской транслитерации (никаких "Skidka", "Akciya", "Сена" вместо "Цена" и т.п.).` +
          `\n  • Каждая буква должна быть читаемой, грамматически верной, без перевёрнутых/перепутанных/искажённых символов.` +
          `\n  • НЕ изобретай слова — используй только реальные слова ${lang} языка с корректным написанием.` +
          (input.format.lang === "kz"
            ? `\n  • Специальные казахские буквы (ә, ғ, қ, ң, ө, ұ, ү, һ, і) рендери точно, не путай с похожими русскими/латинскими.`
            : `\n  • Букву «ё» можно заменять на «е», если модель её плохо рендерит — это допустимо.`) +
          `\n  • Если фраза длинная или сложная — сократи до 2-4 слов; короткий текст рендерится без ошибок чаще.` +
          `\n  • Если вообще не уверен в написании — лучше вообще не пиши текст, оставь только визуал.`,
      );
    }
  }
  if (input.format?.variants) formatLines.push(`Количество вариантов: ${input.format.variants}.`);

  if (input.color && input.color.id && input.color.id !== "auto" && input.color.label) {
    formatLines.push(
      `Основной фирменный цвет: ${input.color.label}${input.color.swatch && input.color.swatch !== "custom" && input.color.swatch !== "auto" ? ` (${input.color.swatch})` : ""}. Используй его как акцент в композиции.`,
    );
  }

  if (input.angles && input.angles.length) {
    formatLines.push(
      `Ракурсы съёмки: ${input.angles.map((a) => `${a.label} (${a.description})`).join(", ")}.`,
    );
  }

  if (input.styleId === "auto" && input.autoCandidates && input.autoCandidates.length) {
    formatLines.push(
      `Возможные форматы на выбор: ${input.autoCandidates.map((c) => c.label).join(", ")}. Выбери оптимальный.`,
    );
  }

  const technicalBrief = [
    base.promptTemplate.replace("{{userBrief}}", userBrief),
    "",
    "Технические параметры:",
    ...formatLines.map((l) => `- ${l}`),
    "",
    "Чего избегать: " + base.avoid.join("; ") + ".",
  ]
    .filter(Boolean)
    .join("\n");

  return {
    structured: base,
    technicalBrief,
    avoid: base.avoid,
  };
}
