export interface StyleBrief {
  id: StyleId;
  label: string;
  /** Композиция кадра: расположение объектов, точки фокуса. */
  composition: string;
  /** Освещение: тип, источник, мягкость, цвет. */
  lighting: string;
  /** Ракурс камеры. */
  cameraAngle: string;
  /** Главный субъект кадра. */
  subject: string;
  /** Настроение / эмоция. */
  mood: string;
  /** Работа с типографикой и текстом на креативе. */
  typography: string;
  /** Цветовая обработка. */
  colorTreatment: string;
  /** Реквизит, окружение. */
  props: string;
  /** Референсы — что вдохновляет визуал. */
  references: string[];
  /** Шаблон промпта. {{userBrief}} подставляется автоматически. */
  promptTemplate: string;
  /** Negative prompt — чего избегать. */
  avoid: string[];
}

